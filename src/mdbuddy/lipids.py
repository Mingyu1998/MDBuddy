"""Lipid names across Martini 2, Martini 3 (2021 release) and the Martini 3 lipidome (2025).

The same four-letter name can mean a different molecule in different Martini versions,
and the same molecule can have different names. Examples from the official naming table:

  * DLPC  - Martini 2 / M3 2021: di-C12:0-C14:0;   lipidome: di-C18:2 (dilinoleoyl)
  * PIPC  - Martini 2 / M3 2021: C16:0/18:2;       lipidome: C16:0/20:2 (C16:0/18:2 is PLPC)
  * POP2  - Martini 2: generic PIP2;               lipidome: PI(3,4)P2 (PI(4,5)P2 is POP6)
  * cardiolipin - Martini 2: CDL0/CDL1/CDL2 (0/1-/2-);  lipidome: TOCL/TMCL (always 2-)

The data in data/lipids.json is generated by tools/build_lipid_db.py from the lipidome
repository's naming spreadsheet, the itp files and COBY's definitions; nothing is typed in
by hand except the documented corrections in that script.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import lru_cache
from importlib import resources
from typing import Optional

LIBRARIES = ("martini2", "martini3_2021", "martini3_lipidome")
LIBRARY_LABELS = {
    "martini2": "Martini 2.x",
    "martini3_2021": "Martini 3 (2021 release lipids)",
    "martini3_lipidome": "Martini 3 lipidome (Pedersen et al. 2025)",
}
# Martini 2 and the 2021 Martini 3 release share one naming convention; the lipidome
# uses its own and records the Martini 2 equivalent of each lipid.
_SAME_CONVENTION = {"martini2", "martini3_2021"}


@lru_cache(maxsize=1)
def database() -> dict:
    with resources.files("mdbuddy").joinpath("data/lipids.json").open() as fh:
        return json.load(fh)


def library(name: str) -> dict:
    return database()["libraries"][name]


def library_for(spec) -> str:
    if spec.cg["forcefield"] != "martini3":
        return "martini2"
    return "martini3_lipidome" if spec.ff_files["martini3_lipids"] == "lipidome" else "martini3_2021"


def lookup(name: str, lib: str) -> Optional[dict]:
    return library(lib).get(name)


def describe(name: str, lib: str) -> str:
    e = lookup(name, lib)
    if e is None:
        return f"{name}: not defined in {LIBRARY_LABELS[lib]}"
    bits = [e.get("common") or e.get("chemistry") or e.get("class") or "?"]
    if e.get("charge") is not None:
        bits.append(f"charge {e['charge']:+g}")
    return f"{name}: " + ", ".join(bits)


def equivalents(name: str, src: str, dst: str) -> list[str]:
    """Names in ``dst`` for the molecule called ``name`` in ``src`` (best match first)."""
    if src == dst:
        return [name] if name in library(dst) else []
    if src in _SAME_CONVENTION and dst in _SAME_CONVENTION:
        return [name] if name in library(dst) else []
    if dst == "martini3_lipidome":
        # src uses Martini 2 naming: lipidome entries list their Martini 2 equivalent(s)
        hits = [(n, e) for n, e in library(dst).items() if name in (e.get("m2") or [])]
        src_chem = (lookup(name, src) or {}).get("chemistry") or ""

        def rank(ne):
            n, e = ne
            chem = e.get("chemistry") or ""
            # same name, then identical chemistry, then the first chemistry the M2 model names
            return (n != name, chem != src_chem, not (chem and src_chem.startswith(chem)), n)

        return [n for n, _ in sorted(hits, key=rank)]
    if src == "martini3_lipidome":
        m2_names = (lookup(name, src) or {}).get("m2") or []
        return [n for n in m2_names if n in library(dst)]
    return []


@dataclass
class LipidCheck:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    renames: dict[str, dict[int, tuple[str, str]]] = field(default_factory=dict)


def check(names: list[str], lib: str) -> LipidCheck:
    """Validate membrane lipid names for one library.

    Errors: unknown names (with suggestions from other libraries) and lipids COBY cannot build.
    Warnings: names that mean a different molecule in another Martini version.
    """
    result = LipidCheck()
    for name in names:
        entry = lookup(name, lib)
        if entry is None:
            hints = []
            for other in LIBRARIES:
                if other == lib or name not in library(other):
                    continue
                eq = equivalents(name, other, lib)
                if eq:
                    hints.append(f"'{name}' is a {LIBRARY_LABELS[other]} name ({describe(name, other)}); "
                                 f"in {LIBRARY_LABELS[lib]} use: " + "; ".join(describe(n, lib) for n in eq))
                else:
                    hints.append(f"'{name}' exists in {LIBRARY_LABELS[other]} ({describe(name, other)}) "
                                 f"but has no equivalent in {LIBRARY_LABELS[lib]}")
            msg = f"lipid {name} is not defined in {LIBRARY_LABELS[lib]}"
            result.errors.append(msg + (":\n      " + "\n      ".join(hints) if hints else
                                        " (check spelling; `mdbuddy lipids search` lists names)"))
            continue

        status = entry["coby"]["status"]
        if status in ("missing", "unsupported"):
            why = entry["coby"].get("reason", "COBY has no definition for it")
            result.errors.append(f"lipid {name} exists in {LIBRARY_LABELS[lib]} but COBY cannot build it ({why})")
        elif status == "rename":
            result.renames[name] = {int(i): (a, b) for i, (a, b) in entry["coby"]["renames"].items()}
        elif status == "unverified":
            result.warnings.append(f"{name}: COBY has a definition but MDBuddy pins no itp to check it against; "
                                   "the atom-name validation after COBY will catch a mismatch")

        if entry.get("note"):
            result.warnings.append(f"{name}: {entry['note']}")
        for other in LIBRARIES:
            o = lookup(name, other)
            if other == lib or o is None or (lib in _SAME_CONVENTION and other in _SAME_CONVENTION):
                continue
            lipidome_entry = entry if lib == "martini3_lipidome" else o
            if not lipidome_entry.get("m2_mapping_known", True):
                result.warnings.append(
                    f"{name} also exists in {LIBRARY_LABELS[other]}, and the official naming table does not say "
                    f"whether it is the same molecule: here {describe(name, lib)}; there {describe(name, other)}")
            elif name not in equivalents(name, lib, other):
                result.warnings.append(
                    f"{name} means a different molecule in {LIBRARY_LABELS[other]}: here {describe(name, lib)}; "
                    f"there {describe(name, other)}")
    return result


def coby_params(name: str, lib: str) -> str:
    return library(lib)[name]["coby_params"]


def itp_files(names: list[str], lib: str) -> list[str]:
    """Parameter files that define ``names`` (in first-use order)."""
    files: list[str] = []
    for n in names:
        f = library(lib)[n].get("itp")
        if f and f not in files:
            files.append(f)
    return files


def search(text: str, lib: Optional[str] = None) -> list[tuple[str, str, dict]]:
    text = text.lower()
    out = []
    for lname in ([lib] if lib else LIBRARIES):
        for name, e in library(lname).items():
            hay = " ".join(str(e.get(k) or "") for k in ("common", "chemistry", "class", "description"))
            if text in name.lower() or text in hay.lower():
                out.append((lname, name, e))
    return out


# --- report -------------------------------------------------------------------------------

def _short_description(desc: str) -> str:
    desc = desc.replace("Martini lipid topology for ", "").replace(", generated using:", "")
    desc = desc.replace("A general model ", "").replace(" lipid corresponding to atomistic ", ", ")
    return desc.rstrip(".")


def _what(e: Optional[dict]) -> str:
    if not e:
        return "–"
    text = (e.get("common") or e.get("chemistry")
            or (_short_description(e["description"]) if e.get("description") else None)
            or e.get("class") or "(no description in the itp)")
    return text.replace("|", "/")


def _charge(e: Optional[dict]) -> Optional[float]:
    return None if not e or e.get("charge") is None else float(e["charge"])


def report_markdown() -> str:
    """Every lipid whose name changed or clashes between versions, as Markdown.

    Written to docs/lipid_name_changes.md by `mdbuddy lipids report`; a test keeps that
    file in sync with data/lipids.json.
    """
    m2, m21, lip = library("martini2"), library("martini3_2021"), library("martini3_lipidome")
    # Martini 2 and the 2021 release share a naming convention; take charges from the 2021
    # itps where the Martini 2 entry has none (same head-group charges).
    old = {}
    for n in sorted(set(m2) | set(m21)):
        e = dict(m2.get(n) or {})
        for k, v in (m21.get(n) or {}).items():
            if e.get(k) is None and k in ("charge", "chemistry", "common", "class"):
                e[k] = v
        e["_src"] = "martini2" if n in m2 else "martini3_2021"
        old[n] = e

    def eq(n):
        return equivalents(n, old[n]["_src"], "martini3_lipidome")

    unlisted = [n for n in old if n in lip and not lip[n].get("m2_mapping_known", True)]
    clashes = [n for n in old if n in lip and n not in eq(n) and n not in unlisted]
    renamed = [n for n in old if eq(n) and n not in eq(n)]
    unchanged = [n for n in old if n in eq(n)]
    no_eq = [n for n in old if not eq(n) and n not in unlisted]
    src = database()["sources"]

    out = [
        "# Lipid name changes: Martini 2 / Martini 3 (2021) → Martini 3 lipidome (2025)",
        "",
        "<!-- Generated by `mdbuddy lipids report` from src/mdbuddy/data/lipids.json. Do not edit by hand. -->",
        "",
        "Martini lipid names are four-letter codes for tails + head group. The Martini 3 lipidome "
        "(Pedersen et al., *ACS Cent. Sci.* 2025, doi:10.1021/acscentsci.5c00755) changed the naming "
        "convention, so **the same name can be a different molecule, and the same molecule can have a "
        "different name.** Martini 2 and the lipids of the original Martini 3 release (2021) share one "
        "convention, so this document compares that convention with the lipidome.",
        "",
        f"Sources: lipid parameters and the official naming spreadsheet "
        f"(`tools/CG-Martini-lipids-naming.xlsx`) from {src['lipidome']}; COBY support from {src['coby']}. "
        "Look up any name with `mdbuddy lipids show NAME`, convert with "
        "`mdbuddy lipids convert NAME --from m2 --to m3`.",
        "",
        "| | Count |",
        "|---|---|",
        f"| Same name, **different molecule** | {len(clashes)} |",
        f"| Same molecule, **new name** in the lipidome | {len(renamed)} |",
        f"| Same name, same molecule | {len(unchanged)} |",
        f"| Same name, lipidome lipid not in the official table (check chemistry) | {len(unlisted)} |",
        f"| No lipidome equivalent recorded | {len(no_eq)} |",
        f"| Lipidome lipids in total | {len(lip)} |",
        "",
        "Martini's 4:1 mapping does not tell C16 from C18, so one Martini 2 lipid often corresponds to "
        "several lipidome lipids (e.g. M2 DPPC = C16:0–C18:0 → DPPC, DSPC, PSPC). They are listed best "
        "chemical match first. Pick the one that matches the atomistic lipid you mean.",
        "",
        "## 1. Same name, different molecule",
        "",
        "Using one of these names with the wrong force field silently gives you a different lipid. "
        "MDBuddy prints a `LIPID NOTE` for each of them during a build.",
        "",
        "| Name | Martini 2 / M3 2021 | M3 lipidome | Lipidome name of the M2 molecule | M2 name of the lipidome molecule |",
        "|---|---|---|---|---|",
    ]
    for n in clashes:
        back = ", ".join(lip[n].get("m2") or []) or "–"
        out.append(f"| **{n}** | {_what(old[n])} | {_what(lip[n])} | {', '.join(eq(n)) or '–'} | {back} |")

    out += [
        "",
        "### Same name, but the lipidome lipid is not in the official naming table",
        "",
        "The official table cannot say whether these are the same molecule. Compare the chemistry yourself.",
        "",
        "| Name | Martini 2 / M3 2021 | M3 lipidome (from the itp header) |",
        "|---|---|---|",
    ]
    out += [f"| {n} | {_what(old[n])} | {_what(lip[n])} |" for n in unlisted]
    out += [
        "",
        "## 2. Same molecule, new name in the lipidome",
        "",
        "| Martini 2 / M3 2021 | Molecule | Lipidome name(s), best match first | Charge | COBY (lipidome) |",
        "|---|---|---|---|---|",
    ]
    for n in renamed:
        targets = eq(n)
        q_old = _charge(old[n])
        charges = []
        for t in targets:
            q_new = _charge(lip[t])
            if q_old is not None and q_new is not None and abs(q_old - q_new) > 1e-6:
                charges.append(f"**{t}: {q_old:+g} → {q_new:+g}**")
        charge = "; ".join(charges) or ("same" if q_old is not None else "–")
        coby = ", ".join(f"{t}: {lip[t]['coby']['status']}" for t in targets)
        out.append(f"| {n} | {_what(old[n])} | {', '.join(targets)} | {charge} | {coby} |")

    out += [
        "",
        "## 3. Same name, same molecule",
        "",
        "The name still means the same molecule, but every lipidome lipid is **re-parameterised**, so "
        "results are not expected to match Martini 2 or the 2021 release exactly. Where the lipidome "
        "also has other lipids with the same Martini 2 mapping they are listed in brackets.",
        "",
    ]
    items = []
    for n in unchanged:
        others = [t for t in eq(n) if t != n]
        items.append(f"{n} ({', '.join(others)})" if others else n)
    out.append(", ".join(items))
    notes = [(n, lip[n]["note"]) for n in unchanged if lip.get(n, {}).get("note")]
    if notes:
        out.append("")
        out += [f"- **{n}**: {note}" for n, note in notes]

    out += [
        "",
        "## 4. No lipidome equivalent in the official table",
        "",
        "The official naming spreadsheet records no lipidome lipid for these Martini 2 / 2021 names. A "
        "chemically close lipid may still exist. Search with `mdbuddy lipids search <chemistry> --ff m3`.",
        "",
        "| Name | Molecule | Same name in the lipidome means |",
        "|---|---|---|",
    ]
    for n in no_eq:
        out.append(f"| {n} | {_what(old[n])} | {_what(lip.get(n)) if n in lip else '–'} |")

    curated = [(n, e["note"]) for n, e in sorted(lip.items()) if e.get("note") and n not in unchanged]
    out += [
        "",
        "## 5. Corrections MDBuddy makes to the official table",
        "",
        "- **Phosphoinositides:** the spreadsheet's \"Martini 2 name\" column repeats the lipidome name "
        "(it lists M2 POP4–POP7, which do not exist). Martini 2 has one generic model per phosphorylation "
        "level with no ring positions, so MDBuddy maps by phosphorylation level. Mapping M2 POP2 to "
        "PI(4,5)P2 (lipidome POP6) is an assumption. Check it against the study you are reproducing.",
        "- **Cardiolipin and cholesterol** are not in the spreadsheet; they were added from the itp headers.",
        "",
    ]
    out += [f"- **{n}**: {note}" for n, note in curated]

    unsupported = sorted(n for n, e in lip.items() if e["coby"]["status"] == "unsupported")
    renames = sorted(n for n, e in lip.items() if e["coby"]["status"] == "rename")
    missing_classes: dict[str, int] = {}
    for e in lip.values():
        if e["coby"]["status"] == "missing":
            missing_classes[e["itp"]] = missing_classes.get(e["itp"], 0) + 1
    m2_missing = sorted(n for n, e in m2.items() if e["coby"]["status"] == "missing")
    out += [
        "",
        f"## 6. What COBY can build ({src['coby']})",
        "",
        "COBY places lipids from its own bead libraries, which must match the itp atom by atom.",
        "",
        f"- **Built correctly after an MDBuddy rename** (COBY uses a wrong atom name at the right position): "
        f"{', '.join(renames)}.",
        f"- **Cannot be built** (COBY's bead count or order differs from the itp): {', '.join(unsupported)}.",
        "- **No COBY definition:** " + ", ".join(f"{k} ({v})" for k, v in sorted(missing_classes.items())) + ".",
        f"- **Martini 2 lipids with no COBY definition:** {', '.join(m2_missing)}.",
        "",
    ]
    return "\n".join(out)
