"""Clean the input structure before martinize2.

Removes OPM dummy atoms, waters, hydrogens and (by default) all hetero groups,
selects chains, resolves alternate locations, and reports gaps so the agent
can tell the user about them.
"""

from __future__ import annotations

from collections import OrderedDict
from pathlib import Path

from .structure import DUMMY_RESNAMES, WATER_RESNAMES, Atom, opm_half_thickness, read_pdb, write_pdb

# Gap detection: CA-CA distance above this (Angstrom) between consecutive residues
CA_GAP_CUTOFF = 4.2

# Heavy atoms of the standard residues (PDB names). martinize2 cannot place a bead whose atoms are
# all missing (it writes nan coordinates), so incomplete side chains must be rebuilt first.
_BACKBONE = ("N", "CA", "C", "O")
HEAVY_ATOMS = {
    "ALA": ("CB",), "ARG": ("CB", "CG", "CD", "NE", "CZ", "NH1", "NH2"), "ASN": ("CB", "CG", "OD1", "ND2"),
    "ASP": ("CB", "CG", "OD1", "OD2"), "CYS": ("CB", "SG"), "GLN": ("CB", "CG", "CD", "OE1", "NE2"),
    "GLU": ("CB", "CG", "CD", "OE1", "OE2"), "GLY": (), "HIS": ("CB", "CG", "ND1", "CD2", "CE1", "NE2"),
    "ILE": ("CB", "CG1", "CG2", "CD1"), "LEU": ("CB", "CG", "CD1", "CD2"), "LYS": ("CB", "CG", "CD", "CE", "NZ"),
    "MET": ("CB", "CG", "SD", "CE"), "PHE": ("CB", "CG", "CD1", "CD2", "CE1", "CE2", "CZ"),
    "PRO": ("CB", "CG", "CD"), "SER": ("CB", "OG"), "THR": ("CB", "OG1", "CG2"),
    "TRP": ("CB", "CG", "CD1", "CD2", "NE1", "CE2", "CE3", "CZ2", "CZ3", "CH2"),
    "TYR": ("CB", "CG", "CD1", "CD2", "CE1", "CE2", "CZ", "OH"), "VAL": ("CB", "CG1", "CG2"),
}
for _alias, _base in (("HID", "HIS"), ("HIE", "HIS"), ("HIP", "HIS"), ("HSD", "HIS"), ("HSE", "HIS"),
                      ("HSP", "HIS"), ("CYX", "CYS")):
    HEAVY_ATOMS[_alias] = HEAVY_ATOMS[_base]
_ALT_NAMES = {("ILE", "CD1"): {"CD"}}  # CHARMM-style names accepted as present

REPAIR_SCRIPT = """\
# Generated by MDBuddy: rebuild missing heavy atoms with PDBFixer (OpenMM), then relax only the
# rebuilt atoms (all atoms present in the input stay fixed). Missing residues/loops are NOT built.
import sys
from openmm import Platform, VerletIntegrator
from openmm.app import ForceField, Modeller, NoCutoff, PDBFile, Simulation
from pdbfixer import PDBFixer

src, dst = sys.argv[1], sys.argv[2]
original = set()
for line in open(src):
    if line.startswith(("ATOM", "HETATM")):
        original.add((line[21].strip(), line[22:26].strip(), line[26].strip(), line[12:16].strip()))

fixer = PDBFixer(filename=src)
fixer.findMissingResidues()
fixer.missingResidues = {{}}
fixer.findMissingAtoms()
fixer.addMissingAtoms(seed={seed})
fixer.addMissingHydrogens(7.0)  # needed for the force field; removed again below

system = ForceField("amber14-all.xml").createSystem(fixer.topology, nonbondedMethod=NoCutoff, constraints=None)
moving = 0
for atom in fixer.topology.atoms():
    key = (atom.residue.chain.id, atom.residue.id, atom.residue.insertionCode.strip(), atom.name)
    if atom.element.symbol != "H" and key in original:
        system.setParticleMass(atom.index, 0.0)  # mass 0 = fixed in OpenMM
    else:
        moving += 1
try:
    platform = Platform.getPlatformByName("CPU")
except Exception:
    platform = Platform.getPlatformByName("Reference")
sim = Simulation(fixer.topology, system, VerletIntegrator(0.001), platform)
sim.context.setPositions(fixer.positions)
before = sim.context.getState(getEnergy=True).getPotentialEnergy()
sim.minimizeEnergy(maxIterations=1000)
state = sim.context.getState(getPositions=True, getEnergy=True)
print(f"relaxed {{moving}} rebuilt/hydrogen atoms; energy {{before}} -> {{state.getPotentialEnergy()}}")

modeller = Modeller(fixer.topology, state.getPositions())
modeller.delete([a for a in modeller.topology.atoms() if a.element.symbol == "H"])
with open(dst, "w") as fh:
    PDBFile.writeFile(modeller.topology, modeller.positions, fh, keepIds=True)
"""


class PrepareError(RuntimeError):
    pass


def _pick_altlocs(atoms: list[Atom]) -> list[Atom]:
    """Keep the first alternate location of each atom (usually 'A')."""
    seen: set = set()
    kept = []
    for a in atoms:
        key = (a.chain, a.resid, a.icode, a.name)
        if a.altloc:
            if key in seen:
                continue
            a.altloc = ""
        seen.add(key)
        kept.append(a)
    return kept


def _find_gaps(atoms: list[Atom]) -> list[dict]:
    gaps = []
    by_chain: "OrderedDict[str, list[Atom]]" = OrderedDict()
    for a in atoms:
        if a.record == "ATOM" and a.name == "CA":
            by_chain.setdefault(a.chain, []).append(a)
    for chain, cas in by_chain.items():
        for prev, cur in zip(cas, cas[1:]):
            d = ((cur.x - prev.x) ** 2 + (cur.y - prev.y) ** 2 + (cur.z - prev.z) ** 2) ** 0.5
            if d > CA_GAP_CUTOFF:
                gaps.append({"chain": chain, "after_resid": prev.resid, "before_resid": cur.resid,
                             "missing_residues": max(cur.resid - prev.resid - 1, 0),
                             "ca_distance": round(d, 2)})
    return gaps


def find_incomplete(atoms: list[Atom]) -> list[dict]:
    """Standard residues with missing heavy atoms (terminal OXT is never required)."""
    residues: "OrderedDict[tuple, dict]" = OrderedDict()
    for a in atoms:
        if a.record != "ATOM":
            continue
        key = (a.chain, a.resid, a.icode)
        residues.setdefault(key, {"resname": a.resname, "names": set()})["names"].add(a.name)
    out = []
    for (chain, resid, icode), r in residues.items():
        expected = HEAVY_ATOMS.get(r["resname"])
        if expected is None:
            continue
        missing = [n for n in _BACKBONE + expected
                   if n not in r["names"] and not (_ALT_NAMES.get((r["resname"], n), set()) & r["names"])]
        if missing:
            out.append({"chain": chain, "resid": resid, "resname": r["resname"], "missing": missing})
    return out


def repair_with_pdbfixer(lock, entry, in_pdb: Path, out_pdb: Path, seed: int) -> None:
    import sys
    script = in_pdb.parent / "repair_pdbfixer.py"
    script.write_text(REPAIR_SCRIPT.format(seed=seed))
    lock.run(entry, [sys.executable, script.name, in_pdb.name, out_pdb.name], cwd=in_pdb.parent,
             log_name="repair_pdbfixer.log")


def prepare(spec, in_pdb: Path, out_pdb: Path) -> dict:
    atoms, header = read_pdb(in_pdb)
    p = spec.protein
    report: dict = {"input_atoms": len(atoms)}

    report["opm_half_thickness_A"] = opm_half_thickness(header)

    dropped: dict[str, int] = {}

    def drop(reason: str) -> None:
        dropped[reason] = dropped.get(reason, 0) + 1

    keep_het = {r.upper() for r in p["keep_hetatm"]}
    chains = set(p["chains"]) if p["chains"] else None
    kept: list[Atom] = []
    for a in atoms:
        if a.resname in DUMMY_RESNAMES:
            drop("opm_dummy")
        elif a.resname in WATER_RESNAMES:
            drop("water")
        elif chains is not None and a.chain not in chains:
            drop("chain_not_selected")
        elif a.is_hydrogen:
            drop("hydrogen")
        elif a.record == "HETATM" and a.resname.upper() not in keep_het:
            drop(f"hetatm:{a.resname}")
        else:
            kept.append(a)
    kept = _pick_altlocs(kept)

    if not kept:
        raise PrepareError("no atoms left after cleaning; check protein.chains and the input file")
    present_chains = list(OrderedDict.fromkeys(a.chain for a in kept))
    if chains is not None:
        missing = sorted(chains - set(present_chains))
        if missing:
            raise PrepareError(f"chains {missing} not found in the input (found {present_chains})")

    # martinize2 needs chain IDs to separate molecules
    for a in kept:
        if not a.chain:
            a.chain = "A"

    gaps = _find_gaps(kept)
    report["incomplete_residues"] = find_incomplete(kept)
    write_pdb(out_pdb, kept, header=[h for h in header if h.startswith("CRYST1")])
    report.update({
        "output_atoms": len(kept),
        "chains": present_chains,
        "dropped": dropped,
        "gaps": gaps,
        "kept_hetatm": sorted({a.resname for a in kept if a.record == "HETATM"}),
    })
    return report
